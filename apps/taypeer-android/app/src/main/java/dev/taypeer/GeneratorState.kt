package dev.taypeer

import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.setValue
import androidx.lifecycle.ViewModel
import androidx.lifecycle.viewModelScope
import dev.taypeer.bridge.*
import kotlinx.coroutines.*

enum class GeneratorMode { PASSWORD, PASSPHRASE }

private data class GeneratorInput(
    val mode: GeneratorMode = GeneratorMode.PASSWORD,
    val length: String = "30", val words: String = "6", val separator: String = "-",
    val uppercase: Boolean = true, val lowercase: Boolean = true,
    val digits: Boolean = true, val punctuation: Boolean = true,
    val excludeSimilar: Boolean = false, val exclusions: String = "",
)

internal interface GeneratorBackend {
    suspend fun password(options: PasswordOptions): GeneratedSecretView
    suspend fun passphrase(words: UByte, separator: String): GeneratedSecretView
}
private object RustGeneratorBackend : GeneratorBackend {
    override suspend fun password(options: PasswordOptions) = generatePasswordView(options)
    override suspend fun passphrase(words: UByte, separator: String) = generatePassphraseView(words, separator)
}

/** In-memory form only. Rust owns sampling, validation, entropy and quality. */
class GeneratorState internal constructor(
    private val backend: GeneratorBackend = RustGeneratorBackend,
    private val workDispatcher: CoroutineDispatcher = Dispatchers.Default,
) : ViewModel() {
    private var input by mutableStateOf(GeneratorInput())
    val mode get() = input.mode
    val passphrase get() = mode == GeneratorMode.PASSPHRASE
    val length get() = input.length
    val words get() = input.words
    val separator get() = input.separator
    val uppercase get() = input.uppercase
    val lowercase get() = input.lowercase
    val digits get() = input.digits
    val punctuation get() = input.punctuation
    val excludeSimilar get() = input.excludeSimilar
    val exclusions get() = input.exclusions
    var generated by mutableStateOf("")
        private set
    var entropyBits by mutableStateOf(0.0); private set
    var quality by mutableStateOf(GeneratedQuality.LOW); private set
    var error by mutableStateOf(false)
    var running by mutableStateOf(false)
        private set
    var revealed by mutableStateOf(false)
    private var generation = 0L
    private var task: Job? = null

    fun selectMode(value: GeneratorMode) = update(input.copy(mode = value))
    fun changeLength(value: String) = update(input.copy(length = value))
    fun changeWords(value: String) = update(input.copy(words = value))
    fun changeSeparator(value: String) = update(input.copy(separator = value))
    fun changeUppercase(value: Boolean) = update(input.copy(uppercase = value))
    fun changeLowercase(value: Boolean) = update(input.copy(lowercase = value))
    fun changeDigits(value: Boolean) = update(input.copy(digits = value))
    fun changePunctuation(value: Boolean) = update(input.copy(punctuation = value))
    fun changeSimilar(value: Boolean) = update(input.copy(excludeSimilar = value))
    fun changeExclusions(value: String) = update(input.copy(exclusions = value))

    private fun update(value: GeneratorInput) {
        if (input == value) return
        input = value
        start(debounce = true)
    }
    fun generate() = start(debounce = false)

    private fun start(debounce: Boolean) {
        val request = ++generation
        task?.cancel()
        clearResult(); error = false; running = false
        val parameters = input
        val count = if (passphrase) parameters.words.toUByteOrNull()?.toUShort() else parameters.length.toUShortOrNull()
        if (count == null) { error = true; return }
        val options = PasswordOptions(count, parameters.uppercase, parameters.lowercase, parameters.digits,
            parameters.punctuation, parameters.excludeSimilar, parameters.exclusions)
        running = true
        task = viewModelScope.launch {
            try {
                // Debounce typing; revoke the previous result before this delay.
                if (debounce) delay(150)
                val value = withContext(workDispatcher) {
                    if (parameters.mode == GeneratorMode.PASSPHRASE) backend.passphrase(count.toUByte(), parameters.separator)
                    else backend.password(options)
                }
                if (generation == request) {
                    generated = value.value; entropyBits = value.entropyBits; quality = value.quality
                }
            } catch (cancelled: CancellationException) { throw cancelled }
            catch (_: Exception) { if (generation == request) error = true }
            finally { if (generation == request) running = false }
        }
    }
    private fun clearResult() { generated = ""; entropyBits = 0.0; quality = GeneratedQuality.LOW; revealed = false }
    fun hideSecret() { revealed = false }
    fun lock() {
        ++generation; task?.cancel(); task = null
        clearResult(); running = false; error = false
    }
    override fun onCleared() { lock(); super.onCleared() }
}
